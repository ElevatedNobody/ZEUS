"""
Phase D - the local industrial knowledge base.

    chunks -> BGE-M3 embeddings -> local SQLite vectors
    query  -> taxonomy expansion -> BGE-M3 query embedding -> cosine shortlist
           -> BGE-Reranker-v2-M3 (or hybrid) evidence ranking
           -> grounded answer with enforced citations

Everything is local: embeddings come from the Ollama daemon on loopback, the
vectors live in database/medha.db beside the rest of ZEUS's data, and the
answer is generated by a local model. There is no vector server, no cloud
index, and no network dependency beyond Ollama itself.

The existing `document_chunks` RAG store and its tools are untouched - this is
a separate, provenance-preserving store for industrial work.
"""

from __future__ import annotations

import time
import uuid
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from core.logger import get_logger
from industrial import provenance, reranker
from industrial.extraction import (CLASS_KNOWLEDGE_CORPUS, CLASS_USER_DOCUMENT,
                                   extract_and_chunk)
from industrial.provenance import Evidence

logger = get_logger("industrial.kb")

MAX_CANDIDATES = 40           # shortlist size handed to the reranker
MIN_DENSE_SCORE = 0.22        # below this a chunk is not worth reranking
DEFAULT_TOP_K = 6


def _cosine(a, b) -> float:
    import numpy as np
    va, vb = np.asarray(a, dtype="float32"), np.asarray(b, dtype="float32")
    denom = float(np.linalg.norm(va) * np.linalg.norm(vb))
    if denom == 0.0:
        return 0.0
    return float(np.dot(va, vb) / denom)


class IndustrialKnowledgeBase:
    def __init__(self):
        self._embed_model: Optional[str] = None

    # ------------------------------------------------------------ embedding

    def embed_model(self) -> str:
        """Which embedding model is in use.

        Resolved by the capability layer, not by the chat model router: an
        embedding model is reached through the embeddings endpoint and has no
        business being selected by the table that picks conversation models.
        """
        if self._embed_model is None:
            from core.capabilities import embedding_provider
            self._embed_model = embedding_provider.resolve() or ""
        return self._embed_model

    def embedding_available(self) -> Tuple[bool, str]:
        """Truthful availability: a REAL embedding call must have succeeded.

        The previous version compared model-name prefixes, which reported an
        installed model as missing (Ollama installs `bge-m3` as
        `bge-m3:latest`) and would equally have reported a broken endpoint as
        fine. Now the answer comes from an actual probe.
        """
        from core.capabilities import Health, embedding_provider
        report = embedding_provider.check()
        if report.health is Health.READY:
            return True, report.model
        return False, report.detail

    def embed(self, text: str) -> Optional[List[float]]:
        from core.capabilities import embedding_provider
        return embedding_provider.embed(text)

    # ------------------------------------------------------------ ingestion

    def ingest_document(self, path: str | Path, document_class: str = CLASS_USER_DOCUMENT,
                        claim_type: Optional[str] = None, options=None,
                        embed: bool = True, replace: bool = True,
                        run_id: Optional[str] = None) -> Dict[str, Any]:
        """Extract -> classify -> normalise -> chunk -> embed -> store.
        Returns a per-document report; never raises on a bad document."""
        from memory.database import (add_industrial_asset, add_industrial_chunks,
                                     delete_industrial_document, init_db, log_ingestion,
                                     upsert_industrial_document)

        path = Path(path).expanduser()
        started = time.perf_counter()
        run_id = run_id or f"run-{uuid.uuid4().hex[:8]}"
        report: Dict[str, Any] = {"file": str(path), "status": "failed", "chunks": 0,
                                  "embedded": 0, "run_id": run_id}

        norm, chunks, raw = extract_and_chunk(path, document_class=document_class,
                                              claim_type=claim_type, options=options)
        if norm is None:
            report["detail"] = (raw.error if raw is not None else "extraction produced nothing")
            log_ingestion(run_id, str(path), "failed", detail=report["detail"])
            return report

        report.update({
            "document_id": norm.document_id, "document_type": norm.document_type,
            "title": norm.title, "pages": norm.page_count,
            "extraction_method": norm.extraction_method,
            "scanned_pages": norm.metadata.get("scanned_pages", []),
            "mean_ocr_confidence": norm.metadata.get("mean_ocr_confidence"),
            "warnings": norm.warnings, "schema_match": norm.metadata.get("schema_match"),
            "missing_required_fields": (norm.metadata.get("schema_fields") is not None and
                                        []) or [],
        })
        if not chunks:
            report["status"] = "skipped"
            report["detail"] = raw.error or "no extractable content"
            log_ingestion(run_id, str(path), "skipped", norm.document_id, 0, report["detail"])
            return report

        init_db()
        if replace:
            delete_industrial_document(norm.document_id)
        upsert_industrial_document(norm.header_row())

        embedded = 0
        if embed:
            ok, detail = self.embedding_available()
            if not ok:
                report["embedding_warning"] = detail
                logger.warning(f"storing chunks without embeddings: {detail}")
            else:
                model = self.embed_model()
                for chunk in chunks:
                    vector = self.embed(chunk["chunk_text"])
                    if vector:
                        chunk["embedding"] = vector
                        chunk["embedding_model"] = model
                        embedded += 1

        add_industrial_chunks(norm.document_id, chunks)
        for asset in norm.assets:
            try:
                add_industrial_asset(norm.document_id, asset.page_number, asset.asset_type,
                                     asset.path, asset.caption, asset.extraction_method)
            except Exception as e:
                logger.debug(f"asset not recorded: {e}")

        report.update({"status": "ok", "chunks": len(chunks), "embedded": embedded,
                       "duration_s": round(time.perf_counter() - started, 2)})
        log_ingestion(run_id, str(path), "ok", norm.document_id, len(chunks),
                      f"{norm.document_type}; {embedded}/{len(chunks)} embedded")
        return report

    def ingest_corpus_file(self, path: str | Path, claim_type: str, run_id: Optional[str] = None,
                           embed: bool = True) -> Dict[str, Any]:
        return self.ingest_document(path, document_class=CLASS_KNOWLEDGE_CORPUS,
                                    claim_type=claim_type, embed=embed, run_id=run_id)

    # ------------------------------------------------------------- retrieval

    def search(self, query: str, top_k: int = DEFAULT_TOP_K,
               document_class: Optional[str] = None,
               claim_types: Optional[List[str]] = None,
               equipment: Optional[str] = None,
               document_type: Optional[str] = None,
               use_rerank: bool = True,
               expand_query: bool = True) -> Tuple[List[Evidence], Dict[str, Any]]:
        """Semantic retrieval over the industrial knowledge base.

        Returns (evidence list, info). `info` records how retrieval ran -
        which embedding model, how many candidates, which reranker backend -
        so a report can state exactly how its evidence was selected."""
        from memory.database import get_industrial_chunks, init_db
        from industrial.taxonomy import get_taxonomy

        info: Dict[str, Any] = {"query": query, "candidates": 0, "returned": 0,
                                "embedding_model": None, "reranker": None, "expansion": None}
        init_db()

        ok, detail = self.embedding_available()
        if not ok:
            info["error"] = detail
            return [], info
        info["embedding_model"] = self.embed_model()

        search_text = query
        if expand_query:
            expansion = get_taxonomy().expand_query(query)
            info["expansion"] = {"terms": expansion["terms"],
                                 "expansions": expansion["expansions"]}
            search_text = expansion["enriched"]

        qvec = self.embed(search_text)
        if qvec is None:
            info["error"] = f"could not embed the query with '{self.embed_model()}'"
            return [], info

        rows = get_industrial_chunks(with_embeddings=True, claim_types=claim_types)
        if document_class:
            rows = [r for r in rows if r.get("document_class") == document_class]
        if document_type:
            rows = [r for r in rows if r.get("document_type") == document_type]
        if equipment:
            needle = equipment.upper().replace("-", "")
            rows = [r for r in rows
                    if needle in (str(r.get("equipment") or "").upper().replace("-", "")
                                  + str(r.get("chunk_text") or "").upper().replace("-", ""))]
        info["searchable_chunks"] = len(rows)
        if not rows:
            info["error"] = ("nothing in the industrial knowledge base matches those filters - "
                             "run scripts/ingest_industrial_knowledge.py first")
            return [], info

        scored = []
        for r in rows:
            emb = r.get("embedding")
            if not emb:
                continue
            s = _cosine(qvec, emb)
            if s >= MIN_DENSE_SCORE:
                r["retrieval_score"] = s
                scored.append(r)
        scored.sort(key=lambda r: r["retrieval_score"], reverse=True)
        candidates = scored[:MAX_CANDIDATES]
        info["candidates"] = len(candidates)
        if not candidates:
            info["note"] = "no chunk passed the minimum relevance threshold"
            return [], info

        if use_rerank:
            ordered, rinfo = reranker.rerank(search_text, candidates)
            info["reranker"] = rinfo
        else:
            ordered = candidates
            info["reranker"] = {"backend": "none", "detail": "reranking disabled"}

        ordered = self._reserve_user_document_slots(ordered, top_k, info)

        evidences: List[Evidence] = []
        for i, row in enumerate(ordered[:top_k], start=1):
            evidences.append(Evidence.from_row(
                row, evidence_id=f"E{i}",
                score=float(row.get("rerank_score", row.get("retrieval_score", 0.0))),
                retrieval_score=float(row.get("retrieval_score", 0.0)),
                rerank_score=row.get("rerank_score")))
        info["returned"] = len(evidences)
        return evidences, info

    @staticmethod
    def _reserve_user_document_slots(ordered: List[Dict[str, Any]], top_k: int,
                                     info: Dict[str, Any]) -> List[Dict[str, Any]]:
        """The plant's own documents must never be crowded out of the answer by
        general industry background. When both classes are relevant, at least
        half of the returned evidence (rounded down, minimum one) is reserved
        for user documents that passed the relevance threshold. Ranking within
        each class is untouched, and if there are no relevant user documents
        the corpus fills every slot as before."""
        if len(ordered) <= top_k:
            return ordered
        head = ordered[:top_k]
        user_in_head = [r for r in head if r.get("document_class") == "user_document"]
        reserve = max(1, top_k // 2)
        if len(user_in_head) >= reserve:
            return head

        user_pool = [r for r in ordered[top_k:] if r.get("document_class") == "user_document"]
        if not user_pool:
            return head

        promote = user_pool[:reserve - len(user_in_head)]
        corpus_in_head = [r for r in head if r.get("document_class") != "user_document"]
        keep_corpus = corpus_in_head[:max(0, top_k - len(user_in_head) - len(promote))]
        merged = user_in_head + promote + keep_corpus
        merged.sort(key=lambda r: r.get("rerank_score", r.get("retrieval_score", 0.0)),
                    reverse=True)
        info["user_document_slots_reserved"] = len(promote)
        return merged[:top_k]

    # --------------------------------------------------------------- answer

    def answer(self, query: str, top_k: int = DEFAULT_TOP_K, task_type: str = "reasoning",
               document_class: Optional[str] = None, claim_types: Optional[List[str]] = None,
               equipment: Optional[str] = None, timeout: float = 120.0,
               system_extra: str = "") -> Dict[str, Any]:
        """Grounded answering with enforced citations. The model is given only
        the retrieved evidence and is not allowed to cite anything else."""
        from core.model_router import model_router
        from core.ollama_client import ollama_client

        evidences, info = self.search(query, top_k=top_k, document_class=document_class,
                                      claim_types=claim_types, equipment=equipment)
        if not evidences:
            return {"answer": None, "error": info.get("error") or info.get("note")
                    or "no relevant evidence found", "evidence": [], "retrieval": info,
                    "grounded": False}

        if not ollama_client.is_available():
            return {"answer": None, "error": "Ollama is not running - start it with 'ollama serve'",
                    "evidence": provenance.evidence_table(evidences), "retrieval": info,
                    "grounded": False}

        model = model_router.route(task_type)
        from security import injection
        injection_flags = []
        for evidence in evidences:
            verdict = injection.scan(evidence.chunk_text)
            if verdict.flagged:
                injection_flags.append({"id": evidence.evidence_id, "source": evidence.filename,
                                        "kinds": verdict.kinds})
        injection.report_flags(injection_flags)
        system = (
            "You are the industrial knowledge assistant of an on-premise engineering "
            "workbench. You answer strictly from supplied plant evidence and you never "
            "invent a document, page, revision, tag or measurement.\n" + provenance.GROUNDING_CONTRACT
            + "\n" + injection.SYSTEM_RULE
        )
        if system_extra:
            system += "\n" + system_extra

        user = (f"EVIDENCE:\n{provenance.build_evidence_prompt(evidences)}\n\n"
                f"QUESTION: {query}\n\n"
                "Answer using only the evidence above, citing evidence ids in square "
                "brackets. If the evidence is insufficient, say precisely what is missing.")

        raw_answer = ollama_client.chat(model, [{"role": "system", "content": system},
                                                {"role": "user", "content": user}],
                                        retries=0, timeout=timeout, task_type="industrial_rag",
                                        purpose="Grounded industrial answer")

        validator = provenance.CitationValidator(evidences)
        report = validator.validate(raw_answer)
        used = report.valid_citations
        return {
            "answer": report.cleaned_answer,
            "model": model,
            "injection_flags": injection_flags,
            "grounded": report.grounded,
            "citation_report": report.to_dict(),
            "sources": provenance.answer_sources(evidences, used or None),
            "evidence": provenance.evidence_table(evidences),
            "retrieval": info,
        }

    # ---------------------------------------------------------------- admin

    def stats(self) -> Dict[str, Any]:
        from memory.database import industrial_kb_stats, init_db
        init_db()
        s = industrial_kb_stats()
        ok, detail = self.embedding_available()
        s["embedding_model"] = self.embed_model()
        s["embedding_ready"] = ok
        s["embedding_detail"] = detail
        s["reranker"] = reranker.status()
        return s

    def list_documents(self) -> List[dict]:
        from memory.database import init_db, list_industrial_documents
        init_db()
        return list_industrial_documents()

    def forget(self, document_id: str) -> int:
        from memory.database import delete_industrial_document, init_db
        init_db()
        return delete_industrial_document(document_id)

    def clear(self) -> int:
        from memory.database import clear_industrial_knowledge_base, init_db
        init_db()
        return clear_industrial_knowledge_base()

    def reembed_missing(self, limit: int = 2000) -> Dict[str, Any]:
        """Embed chunks that were stored while Ollama was unavailable, so an
        ingest done with the daemon down can be completed later without
        re-parsing the documents."""
        from memory.database import get_connection, init_db
        import json as _json

        init_db()
        ok, detail = self.embedding_available()
        if not ok:
            return {"embedded": 0, "error": detail}
        model = self.embed_model()
        conn = get_connection()
        try:
            rows = conn.execute(
                "SELECT id, chunk_text FROM industrial_chunks WHERE embedding IS NULL LIMIT ?",
                (limit,)).fetchall()
        finally:
            conn.close()

        done = 0
        for row in rows:
            vec = self.embed(row["chunk_text"])
            if not vec:
                continue
            conn = get_connection()
            try:
                conn.execute("UPDATE industrial_chunks SET embedding = ?, embedding_model = ? "
                             "WHERE id = ?", (_json.dumps(vec), model, row["id"]))
                conn.commit()
            finally:
                conn.close()
            done += 1
        return {"embedded": done, "pending": max(0, len(rows) - done), "model": model}


