def available_datasets() -> List[str]:
    return sorted(_DATASETS)


def export_dataset_xlsx(dataset: str, filename: str = "", equipment_reference: str = "",
                        open_after: bool = True) -> Dict[str, Any]:
    """Export one plant dataset to a real .xlsx with a header row, a frozen
    pane, an autofilter and sized columns."""
    key = (dataset or "").strip().lower()
    if key not in _DATASETS:
        return {"error": f"Unknown dataset '{dataset}'",
                "available": available_datasets()}
    data = _DATASETS[key]()
    rows = data["rows"]

    if equipment_reference:
        found = pd.resolve_equipment(equipment_reference)
        if not found:
            return {"error": f"No equipment matching '{equipment_reference}'"}
        tag = found["tag"].lower()
        rows = [r for r in rows
                if str(r.get("equipment_tag") or r.get("tag") or "").lower() == tag]

    try:
        from openpyxl import Workbook
        from openpyxl.styles import Alignment, Font, PatternFill
        from openpyxl.utils import get_column_letter
    except ImportError:
        return {"error": "openpyxl is not installed - run: pip install openpyxl"}

    workbook = Workbook()
    sheet = workbook.active
    sheet.title = data["title"][:31]

    columns = data["columns"]
    header_fill = PatternFill("solid", fgColor="1F3864")
    header_font = Font(bold=True, color="FFFFFF")
    for index, column in enumerate(columns, start=1):
        cell = sheet.cell(row=1, column=index, value=column.replace("_", " ").title())
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    for row_index, row in enumerate(rows, start=2):
        for col_index, column in enumerate(columns, start=1):
            value = row.get(column)
            if isinstance(value, (int, float)) or value is None:
                sheet.cell(row=row_index, column=col_index, value=value)
            else:
                sheet.cell(row=row_index, column=col_index, value=str(value))

    last_column = get_column_letter(len(columns))
    sheet.freeze_panes = "A2"
    if rows:
        sheet.auto_filter.ref = f"A1:{last_column}{len(rows) + 1}"
    for index, column in enumerate(columns, start=1):
        longest = max([len(str(column))] +
                      [len(str(r.get(column) or "")) for r in rows[:200]] or [10])
        sheet.column_dimensions[get_column_letter(index)].width = min(max(longest + 2, 10), 55)

    # A summary sheet that says where the numbers came from - a spreadsheet
    # that leaves the shop floor should carry its own provenance.
    meta = workbook.create_sheet("About")
    demo_rows = sum(1 for r in rows if str(r.get("source")) == pd.DEMO)
    for index, (label, value) in enumerate([
        ("Dataset", data["title"]),
        ("Rows exported", len(rows)),
        ("Generated", _stamp()),
        ("Generated by", "ZEUS Autonomous AI Command & Intelligence System (local, offline)"),
        ("Rows marked DEMO", demo_rows),
        ("Note", "DEMO rows are generated sample data, not real plant measurements."
                 if demo_rows else "No DEMO rows in this export."),
    ], start=1):
        meta.cell(row=index, column=1, value=label).font = Font(bold=True)
        meta.cell(row=index, column=2, value=value)
    meta.column_dimensions["A"].width = 22
    meta.column_dimensions["B"].width = 70

    out_dir = office.documents_dir(SUBFOLDER)
    stem = office.safe_stem(filename or f"{key}_export", f"{key}_export")
    path = office.unique_path(out_dir, stem, "xlsx")
    workbook.save(str(path))
    return office.finish(path, "xlsx", open_after=open_after,
                         extra={"dataset": key, "rows": len(rows), "demo_rows": demo_rows})


def export_dataset_csv(dataset: str, filename: str = "",
                       open_after: bool = False) -> Dict[str, Any]:
    key = (dataset or "").strip().lower()
    if key not in _DATASETS:
        return {"error": f"Unknown dataset '{dataset}'", "available": available_datasets()}
    import csv
    data = _DATASETS[key]()
    out_dir = office.documents_dir(SUBFOLDER)
    path = office.unique_path(out_dir, office.safe_stem(filename or f"{key}_export"), "csv")
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=data["columns"], extrasaction="ignore")
        writer.writeheader()
        for row in data["rows"]:
            writer.writerow({c: row.get(c) for c in data["columns"]})
    return office.finish(path, "csv", open_after=open_after,
                         extra={"dataset": key, "rows": len(data["rows"])})


