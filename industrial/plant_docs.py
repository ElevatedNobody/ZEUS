_DATASETS: Dict[str, Callable[[], Dict[str, Any]]] = {}


def _dataset(name: str):
    def wrap(fn):
        _DATASETS[name] = fn
        return fn
    return wrap


@_dataset("equipment")
def _ds_equipment() -> Dict[str, Any]:
    rows = pd.list_equipment(limit=10000)
    return {"title": "Equipment", "rows": rows,
            "columns": ["tag", "name", "equipment_type", "location", "unit", "status",
                        "criticality", "manufacturer", "model", "installed_on", "source"]}


