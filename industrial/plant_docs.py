def _add_bullet_slide(deck, title: str, bullets: List[str]):
    from pptx.util import Pt
    layout = deck.slide_layouts[1]
    slide = deck.slides.add_slide(layout)
    slide.shapes.title.text = title
    body = slide.placeholders[1].text_frame
    body.clear()
    for index, line in enumerate(bullets or ["No data"]):
        para = body.paragraphs[0] if index == 0 else body.add_paragraph()
        para.text = str(line)[:180]
        para.level = 0
        for run in para.runs:
            run.font.size = Pt(16)
    return slide


def operations_deck_pptx(filename: str = "", narrative: bool = True,
                         open_after: bool = True) -> Dict[str, Any]:
    """A management deck built from the plant tables."""
    try:
        from pptx import Presentation
        from pptx.util import Inches, Pt
    except ImportError:
        return {"error": "python-pptx is not installed - run: pip install python-pptx"}

    summary = ops.operations_summary()
    alerts = ops.alert_overview()
    maintenance = ops.maintenance_overview(limit=200)
    inventory = ops.inventory_summary()
    safety = ops.safety_overview()
    banner = _demo_banner(summary.get("provenance", {}))

    deck = Presentation()
    title_slide = deck.slides.add_slide(deck.slide_layouts[0])
    title_slide.shapes.title.text = "Operations and Maintenance Status"
    subtitle = title_slide.placeholders[1]
    subtitle.text = f"ZEUS Autonomous AI Command & Intelligence System\n{_stamp()}"
    if banner:
        box = title_slide.shapes.add_textbox(Inches(0.6), Inches(6.3), Inches(9), Inches(0.6))
        box.text_frame.text = banner
        for para in box.text_frame.paragraphs:
            for run in para.runs:
                run.font.size = Pt(11)
                run.font.bold = True

    _add_bullet_slide(deck, "Plant status", [
        f"{summary['equipment_operational']} of {summary['equipment_total']} items operational"
        + (f" ({summary['availability_pct']}%)" if summary["availability_pct"] else ""),
        f"{summary['equipment_in_maintenance']} in maintenance, "
        f"{summary['equipment_shutdown']} shut down",
        f"{summary['open_alerts']} open alerts",
        f"{summary['maintenance_due_30d']} maintenance items due within 30 days",
    ])

    _add_bullet_slide(deck, "By unit", [
        f"{unit}: " + ", ".join(f"{n} {state}" for state, n in states.items())
        for unit, states in sorted(summary["by_unit"].items())
    ])

    _add_bullet_slide(deck, "Open alerts", [
        f"[{a['severity'].upper()}] {a.get('equipment_tag') or '-'}: {a['description']}"
        for a in alerts["alerts"][:8]
    ] or ["No open alerts"])

    _add_bullet_slide(deck, "Maintenance", [
        f"{maintenance['record_count']} records, {maintenance['total_hours']} hours",
    ] + [f"{k}: {v}" for k, v in sorted(maintenance["by_type"].items())]
      + [f"Due within 30 days: {len(maintenance['due_within_30_days'])}"])

    _add_bullet_slide(deck, "Spares and inventory", [
        f"{inventory['item_count']} stock lines, {inventory['total_units']} units",
        f"{inventory['below_minimum_count']} lines at or below minimum stock",
    ] + [f"Below minimum: {i['part_number']} ({i['quantity']}/{i['minimum_stock']})"
         for i in inventory["below_minimum"][:5]])

    _add_bullet_slide(deck, "Safety position", [
        f"{len(safety['critical_open'])} critical open alerts",
        f"{len(safety['overdue_inspections'])} overdue inspections",
        f"{len(safety['permits_awaiting_approval'])} permits awaiting approval",
        f"{len(safety['active_isolations'])} active isolations",
    ])

    narrative_used = False
    if narrative:
        text = _narrative(
            f"Plant status: {ops.operations_status_text()}\n"
            f"Top alerts: " + "; ".join(a["description"] for a in alerts["alerts"][:5]) +
            "\n\nGive exactly 4 short bullet points a plant manager should take away. "
            "One line each, no preamble.",
            system="You are a plant operations manager. Be concise and factual.")
        if text:
            bullets = [line.lstrip("-* ").strip() for line in text.splitlines()
                       if line.strip()][:6]
            if bullets:
                _add_bullet_slide(deck, "Management summary", bullets)
                narrative_used = True

    _add_bullet_slide(deck, "Data sources", [
        "All figures come from the local ZEUS database.",
        banner or "No DEMO rows in this deck.",
        "No live plant historian is connected to this workstation.",
        "Generated offline - no data left this machine.",
    ])

    out_dir = office.documents_dir(SUBFOLDER)
    path = office.unique_path(out_dir, office.safe_stem(filename or "operations_status",
                                                        "operations_status"), "pptx")
    deck.save(str(path))
    return office.finish(path, "pptx", open_after=open_after,
                         extra={"narrative_included": narrative_used,
                                "demo_data": bool(banner)})


def equipment_deck_pptx(equipment_reference: str, filename: str = "",
                        open_after: bool = True) -> Dict[str, Any]:
    dossier = ops.equipment_dossier(equipment_reference)
    if dossier.get("error"):
        return dossier
    try:
        from pptx import Presentation
    except ImportError:
        return {"error": "python-pptx is not installed - run: pip install python-pptx"}

    item = dossier["equipment"]
    banner = _demo_banner(dossier.get("provenance", {}))
    deck = Presentation()
    title_slide = deck.slides.add_slide(deck.slide_layouts[0])
    title_slide.shapes.title.text = f"{item['tag']} - {item['name']}"
    title_slide.placeholders[1].text = f"Equipment review\n{_stamp()}"

    _add_bullet_slide(deck, "Equipment", [
        f"Tag: {item['tag']}", f"Type: {item.get('equipment_type')}",
        f"Location: {item.get('location')}", f"Status: {item.get('status')}",
        f"Criticality: {item.get('criticality')}",
        f"Manufacturer: {item.get('manufacturer')} {item.get('model') or ''}",
    ])
    _add_bullet_slide(deck, "Maintenance history", [
        f"{r.get('performed_on')} [{r.get('maintenance_type')}] {r.get('description')}"
        for r in dossier["maintenance_records"][:8]] or ["No records"])
    _add_bullet_slide(deck, "Inspections", [
        f"{i.get('inspected_on')} {i.get('inspection_type')}: {i.get('result')} - "
        f"{i.get('findings')}" for i in dossier["inspections"][:6]] or ["No inspections"])
    _add_bullet_slide(deck, "Open alerts", [
        f"[{a['severity'].upper()}] {a['description']}" for a in dossier["open_alerts"]]
        or ["No open alerts"])
    _add_bullet_slide(deck, "Spare parts", [
        f"{s['part_number']}: {s['quantity']} {s.get('unit') or ''} "
        f"(min {s.get('minimum_stock')})" for s in dossier["spare_parts"]] or ["None linked"])
    if banner:
        _add_bullet_slide(deck, "Data source", [banner])

    out_dir = office.documents_dir(SUBFOLDER)
    path = office.unique_path(out_dir,
                              office.safe_stem(filename or f"equipment_review_{item['tag']}"),
                              "pptx")
    deck.save(str(path))
    return office.finish(path, "pptx", open_after=open_after,
                         extra={"equipment": item["tag"], "demo_data": bool(banner)})
