def _docx_document(title: str, subtitle: str = "", banner: str = ""):
    from docx import Document
    from docx.shared import Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    doc = Document()
    doc.add_heading(title, level=0)
    if subtitle:
        para = doc.add_paragraph(subtitle)
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        for run in para.runs:
            run.italic = True
    if banner:
        warning = doc.add_paragraph(banner)
        for run in warning.runs:
            run.bold = True
            run.font.color.rgb = RGBColor(0xB0, 0x30, 0x00)
            run.font.size = Pt(9)
    return doc


def _docx_table(doc, headers: List[str], rows: List[List[Any]]):
    if not rows:
        doc.add_paragraph("No records.")
        return
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Light Grid Accent 1"
    for cell, header in zip(table.rows[0].cells, headers):
        cell.text = str(header)
        for para in cell.paragraphs:
            for run in para.runs:
                run.bold = True
    for row in rows:
        cells = table.add_row().cells
        for cell, value in zip(cells, row):
            cell.text = "" if value is None else str(value)
    doc.add_paragraph()


def maintenance_report_docx(equipment_reference: str = "", filename: str = "",
                            narrative: bool = True, open_after: bool = True) -> Dict[str, Any]:
    """Maintenance report for one item, or for the whole plant."""
    overview = ops.maintenance_overview(equipment_reference, limit=100)
    if overview.get("error"):
        return overview
    tag = overview["equipment"]
    dossier = ops.equipment_dossier(equipment_reference) if equipment_reference else {}
    banner = _demo_banner(overview.get("provenance", {}))

    title = f"Maintenance Report - {tag}"
    doc = _docx_document(title, f"Generated by ZEUS on {_stamp()}", banner or "")

    if dossier.get("equipment"):
        item = dossier["equipment"]
        doc.add_heading("Equipment", level=1)
        _docx_table(doc, ["Field", "Value"], [
            ["Tag", item["tag"]], ["Name", item["name"]],
            ["Type", item.get("equipment_type")], ["Location", item.get("location")],
            ["Unit", item.get("unit")], ["Status", item.get("status")],
            ["Criticality", item.get("criticality")],
            ["Manufacturer", item.get("manufacturer")], ["Model", item.get("model")],
            ["Installed", item.get("installed_on")],
        ])

    doc.add_heading("Summary", level=1)
    doc.add_paragraph(
        f"{overview['record_count']} maintenance records on file, totalling "
        f"{overview['total_hours']} recorded hours. "
        f"{len(overview['open_items'])} open items, "
        f"{len(overview['due_within_30_days'])} due within 30 days.")
    if overview["by_type"]:
        _docx_table(doc, ["Maintenance type", "Records"],
                    [[k, v] for k, v in sorted(overview["by_type"].items())])

    doc.add_heading("Maintenance history", level=1)
    _docx_table(doc, ["Date", "Type", "Description", "Technician", "Hours", "Status"],
                [[r.get("performed_on"), r.get("maintenance_type"), r.get("description"),
                  r.get("technician"), r.get("duration_hours"), r.get("status")]
                 for r in overview["records"]])

    if dossier.get("inspections"):
        doc.add_heading("Inspection history", level=1)
        _docx_table(doc, ["Date", "Type", "Result", "Findings", "Next due"],
                    [[i.get("inspected_on"), i.get("inspection_type"), i.get("result"),
                      i.get("findings"), i.get("next_due")] for i in dossier["inspections"]])

    open_alerts = dossier.get("open_alerts") or []
    if open_alerts:
        doc.add_heading("Open alerts", level=1)
        _docx_table(doc, ["Alert", "Severity", "Raised", "Description"],
                    [[a["alert_id"], a["severity"], a["raised_at"], a["description"]]
                     for a in open_alerts])

    if overview["due_within_30_days"]:
        doc.add_heading("Due within 30 days", level=1)
        _docx_table(doc, ["Equipment", "Due", "Type", "Description"],
                    [[r["equipment_tag"], r.get("next_due"), r.get("maintenance_type"),
                      r.get("description")] for r in overview["due_within_30_days"]])

    narrative_used = False
    if narrative:
        facts = "\n".join(
            f"- {r.get('performed_on')} [{r.get('maintenance_type')}] {r.get('description')}"
            f" | findings: {r.get('findings') or 'none recorded'}"
            for r in overview["records"][:20])
        text = _narrative(
            f"Equipment: {tag}\nMaintenance records:\n{facts}\n\n"
            "Write a short reliability assessment (3 short paragraphs): what the history "
            "shows, the main risk, and a recommended next action. Refer only to the records "
            "above.")
        if text:
            doc.add_heading("Assessment", level=1)
            for para in text.split("\n\n"):
                if para.strip():
                    doc.add_paragraph(para.strip())
            narrative_used = True
        else:
            doc.add_heading("Assessment", level=1)
            doc.add_paragraph("Narrative assessment was not generated: the local model "
                              "(Ollama) was not reachable. The factual record above is "
                              "complete and unaffected.")

    doc.add_paragraph()
    footer = doc.add_paragraph(f"Generated locally by ZEUS - {_stamp()} - no data left "
                               f"this machine.")
    for run in footer.runs:
        run.italic = True

    out_dir = office.documents_dir(SUBFOLDER)
    stem = office.safe_stem(filename or f"maintenance_report_{tag}", "maintenance_report")
    path = office.unique_path(out_dir, stem, "docx")
    doc.save(str(path))
    return office.finish(path, "docx", open_after=open_after,
                         extra={"equipment": tag, "records": overview["record_count"],
                                "narrative_included": narrative_used,
                                "demo_data": bool(banner)})


def safety_report_docx(filename: str = "", narrative: bool = True,
                       open_after: bool = True) -> Dict[str, Any]:
    overview = ops.safety_overview()
    banner = _demo_banner(overview.get("provenance", {}))
    doc = _docx_document("Safety Status Report", f"Generated by ZEUS on {_stamp()}",
                         banner or "")

    doc.add_heading("Scope", level=1)
    doc.add_paragraph(overview["caution"])

    doc.add_heading("Critical open alerts", level=1)
    _docx_table(doc, ["Alert", "Equipment", "Category", "Raised", "Description"],
                [[a["alert_id"], a.get("equipment_tag"), a.get("category"), a.get("raised_at"),
                  a["description"]] for a in overview["critical_open"]])

    doc.add_heading("Safety and compliance alerts", level=1)
    _docx_table(doc, ["Alert", "Equipment", "Severity", "Description"],
                [[a["alert_id"], a.get("equipment_tag"), a["severity"], a["description"]]
                 for a in overview["open_safety_alerts"]])

    doc.add_heading("Overdue inspections", level=1)
    _docx_table(doc, ["Equipment", "Type", "Last inspected", "Was due", "Recommendation"],
                [[i["equipment_tag"], i.get("inspection_type"), i.get("inspected_on"),
                  i.get("next_due"), i.get("recommendation")]
                 for i in overview["overdue_inspections"]])

    doc.add_heading("Permits awaiting approval", level=1)
    _docx_table(doc, ["Permit", "Type", "Equipment", "Requested by", "Description"],
                [[p["permit_id"], p.get("permit_type"), p.get("equipment_tag"),
                  p.get("requested_by"), p.get("description")]
                 for p in overview["permits_awaiting_approval"]])

    doc.add_heading("Active isolations (LOTO)", level=1)
    _docx_table(doc, ["LOTO", "Equipment", "Status", "Applied by", "Verified by"],
                [[l["loto_id"], l["equipment_tag"], l["isolation_status"], l.get("applied_by"),
                  l.get("verified_by")] for l in overview["active_isolations"]])

    narrative_used = False
    if narrative:
        text = _narrative(
            "Open critical alerts: "
            + "; ".join(a["description"] for a in overview["critical_open"][:10])
            + "\nOverdue inspections: "
            + "; ".join(f"{i['equipment_tag']} {i.get('inspection_type')}"
                        for i in overview["overdue_inspections"][:10])
            + "\n\nWrite two short paragraphs summarising the safety position and the "
              "priority actions. Use only the items listed. Do not state regulatory "
              "requirements you were not given.")
        if text:
            doc.add_heading("Summary", level=1)
            for para in text.split("\n\n"):
                if para.strip():
                    doc.add_paragraph(para.strip())
            narrative_used = True

    out_dir = office.documents_dir(SUBFOLDER)
    path = office.unique_path(out_dir, office.safe_stem(filename or "safety_report",
                                                        "safety_report"), "docx")
    doc.save(str(path))
    return office.finish(path, "docx", open_after=open_after,
                         extra={"critical_alerts": len(overview["critical_open"]),
                                "overdue_inspections": len(overview["overdue_inspections"]),
                                "narrative_included": narrative_used,
                                "demo_data": bool(banner)})


def inspection_note_docx(equipment_reference: str, findings: str = "",
                         recommendation: str = "", approver: str = "",
                         filename: str = "", open_after: bool = True) -> Dict[str, Any]:
    """An approval note: states what was found and leaves a signature block.
    Nothing is marked approved - a person signs it."""
    dossier = ops.equipment_dossier(equipment_reference)
    if dossier.get("error"):
        return dossier
    item = dossier["equipment"]
    banner = _demo_banner(dossier.get("provenance", {}))
    doc = _docx_document(f"Inspection Approval Note - {item['tag']}",
                         f"Generated by ZEUS on {_stamp()}", banner or "")

    doc.add_heading("Equipment", level=1)
    _docx_table(doc, ["Field", "Value"],
                [["Tag", item["tag"]], ["Name", item["name"]],
                 ["Location", item.get("location")], ["Status", item.get("status")],
                 ["Criticality", item.get("criticality")]])

    doc.add_heading("Findings", level=1)
    doc.add_paragraph(findings or (dossier["inspections"][0].get("findings")
                                   if dossier.get("inspections") else "No findings recorded."))

    doc.add_heading("Recommendation", level=1)
    doc.add_paragraph(recommendation or (dossier["inspections"][0].get("recommendation")
                                         if dossier.get("inspections")
                                         else "No recommendation recorded."))

    doc.add_heading("Approval", level=1)
    _docx_table(doc, ["Role", "Name", "Signature", "Date"],
                [["Prepared by", "ZEUS (generated)", "", _stamp()],
                 ["Reviewed by", approver or "", "", ""],
                 ["Approved by", "", "", ""]])
    note = doc.add_paragraph("This note is not approved until a competent person signs it. "
                             "ZEUS does not approve inspection findings.")
    for run in note.runs:
        run.bold = True

    out_dir = office.documents_dir(SUBFOLDER)
    path = office.unique_path(out_dir,
                              office.safe_stem(filename or f"approval_note_{item['tag']}",
                                               "approval_note"), "docx")
    doc.save(str(path))
    return office.finish(path, "docx", open_after=open_after,
                         extra={"equipment": item["tag"], "demo_data": bool(banner)})


