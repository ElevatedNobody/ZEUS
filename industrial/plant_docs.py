"""
Industrial documents: turn stored plant data into real DOCX, XLSX and PPTX
files.

This module owns no document machinery of its own. It builds structured content
from the plant tables and writes it with the same python-docx / openpyxl /
python-pptx path the rest of ZEUS uses, finishing through core.office.finish()
so every file is verified before anyone is told it exists.

Deliberate design point: these generators work WITHOUT a language model. A
maintenance report is assembled from maintenance records, not written by a
model, so it still works when Ollama is down - and the numbers in it are the
numbers in the database. When Ollama IS available, `narrative=True` adds an
analysis section on top of the factual tables; if the model is unreachable the
report is still produced, with a line saying the narrative was skipped.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Callable, Dict, List, Optional

from core.logger import get_logger
from core import office
from industrial import plant_data as pd
from industrial import plant_ops as ops

logger = get_logger("industrial.docs")

SUBFOLDER = "Industrial"


def _stamp() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M")


def _demo_banner(provenance: Dict[str, Any]) -> Optional[str]:
    if provenance and provenance.get("contains_demo_data"):
        return ("DEMO DATA - the records in this document are generated sample data, "
                "not measurements from a real plant.")
    return None


def _narrative(prompt: str, system: str = "") -> Optional[str]:
    """Optional LLM enrichment. Returns None when the model is unavailable -
    the caller carries on and says so, rather than failing the whole document."""
    try:
        from core.ollama_client import ollama_client
        from core.model_router import model_router
        if not ollama_client.is_available():
            return None
        model = model_router.route("reasoning")
        if not model:
            return None
        text = ollama_client.chat(model, [
            {"role": "system", "content": system or
             "You are a reliability engineer. Write factual, concise analysis. "
             "Use only the data provided. Do not invent measurements."},
            {"role": "user", "content": prompt},
        ], retries=0, timeout=180.0)
        if not text or text.strip().startswith("["):
            return None
        return text.strip()
    except Exception as e:
        logger.debug(f"narrative skipped: {e}")
        return None


